def for_kind(kind):
    """`kind` 是 `"unit"` 时返回单位俗名表，其余返回科技俗名表。"""
    return UNIT_ALIASES if kind == "unit" else TECH_ALIASES


def target(word, kind):
    """这个词在这类记录里指向哪个编号；没收录返回 None。"""
    return for_kind(kind).get((word or "").strip().lower())
