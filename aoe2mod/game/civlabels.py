#: How many slots one civ record holds.  Measured, not assumed.
SLOTS = 601


def label(slot):
    """Best available name for one slot: 中文, else the English name."""
    got = RESOURCE_ZH.get(slot)
    if got:
        return got
    got = RESOURCE_EN.get(slot)
    if got:
        return got + "（未译）"
    return "资源 %d（游戏没有给名字）" % (slot,)


def is_live(slot):
    return slot in _LIVE


def differs(slot):
    return slot in _VARY


_LIVE = frozenset(LIVE)
_VARY = frozenset(VARY)

