"""The 601 numbers a civilization record carries, and which ones matter.

A civ record in `empires2_x2_p1.dat` is six scalars and then a
601-entry `float` array.  63 civilizations x 601 = 37,863 numbers, and
no tool has ever shown them, because AGE3 shows them as
`Resources[0]`..`Resources[600]` -- a wall of indices with no meaning.

Measured on the shipped file:

  - 65 of the 601 slots are non-zero in at least one civilization;
  - 24 change between civilizations;
  - the other 536 are zero in all 63, so editing one changes nothing
    anybody can observe.

That measurement is what lets the editor sort them: the slots with a
value come first and the 536 empty ones stay behind a disclosure,
instead of the player scrolling 601 rows of 0 to find 伐木效率.

`RESOURCE_EN` comes from the AGE3 research dump in the repository
(`AGE3-全量数据/age3.sqlite`, table `civ_resource`) -- the same source
AGE3 itself gets its field names from, so the two tools agree on what
slot 189 is called.  `RESOURCE_ZH` is hand-written and deliberately
covers only the slots that hold a value: translating an always-zero
slot would be inventing a name for a number nobody can see.

Generated by `_probe/_tmp/gen_civlabels.py`; edit that, not this.
"""

