"""Is `futuravailableunits.json` an AUTHORITY or a DERIVED CACHE of the tree?

This is the question that decides what `unit.availability` has to write.  If the
panel file is derived from `CivTechTrees/<CIV>.json`, then editing the tree is
the correct lever and the panel follows; if it is an independent authority, the
tree edit can never show up and the intent must write this file instead.

Settle it by structure rather than by guessing from the name:

  1. Does every (civ, unit) the panel lists sit under the SAME Building ID the
     civ's tree row gives for that unit?  A generator that walks the tree and
     buckets by `Building ID` produces exactly that; two independent files that
     merely agree in spirit produce a scattering of mismatches.
  2. Does the panel carry UI-DISPLAY fields (`PrereqStringID`, `PrereqIconSet`,
     `PrereqStyle`, `RequiredTechID`) that a build menu has no use for but a
     greyed-out tech-tree row needs?
  3. What is the RequiredAge spread?  A build menu shows what you can build
     NOW; a "future available" list spans ages on purpose.

The 7 omissions found earlier (Goths Huskarl, Huns Tarkan, ...) are the
counter-evidence this probe has to explain rather than paper over: they are all
research-gated unique units, which is exactly what a tree-walking generator
would miss if it did not follow `tech.effect`.

Run:  python _probe/probe_fu_derivation.py
"""
import json
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

import aoe2mod.api as A  # noqa: E402
from aoe2mod.game import civtechtrees as CT  # noqa: E402

FU_REL = os.path.join("resources", "_common", "dat", "futuravailableunits.json")


def main():
    tk = A.open_toolkit()
    fu = json.loads(open(os.path.join(tk.game_root, FU_REL), "rb")
                    .read().decode("utf-8-sig"))
    trees = CT.load_trees(tk.game_root)

    by_tree = {}
    for k in fu:
        cand = CT.civ_file_stem(k)
        if cand in trees:
            by_tree[cand] = k

    # ---- 1. Building ID agreement -----------------------------------------
    agree = disagree = no_row = 0
    examples = []
    for civ in sorted(by_tree):
        for blk in fu[by_tree[civ]].get("Buildings", []):
            bid = blk.get("ID")
            for u in blk.get("Units", []):
                uid = u.get("ID")
                row = CT.row_for(trees[civ], uid)
                if row is None:
                    no_row += 1
                    if len(examples) < 8:
                        examples.append(("no tree row", civ, uid, bid))
                    continue
                tb = row.get("Building ID")
                if tb is not None and int(tb) == int(bid):
                    agree += 1
                else:
                    disagree += 1
                    if len(examples) < 8:
                        examples.append(("building differs", civ, uid,
                                         "panel %s vs tree %s" % (bid, tb)))
    print("(civ, building, unit) triples in the panel file:")
    print("  building matches the civ's tree row : %d" % agree)
    print("  building DIFFERS from the tree row  : %d" % disagree)
    print("  unit has NO tree row for that civ   : %d" % no_row)
    for e in examples:
        print("    %-16s %-14s %-6s %s" % e)
    print()

    # ---- 2. Display fields -------------------------------------------------
    keys = Counter()
    for civ in fu:
        for blk in fu[civ].get("Buildings", []):
            for u in blk.get("Units", []):
                for k in u:
                    keys[k] += 1
    total_units = sum(keys.values())
    print("unit-entry keys across all civs (%d entries):" % total_units)
    for k, n in keys.most_common():
        print("  %-20s %6d" % (k, n))
    ui_only = [k for k in ("PrereqStringID", "PrereqIconSet", "PrereqStyle",
                           "PrereqTech", "RequiredTechID", "RequiredAge")
               if k in keys]
    print("  UI/tech-display fields present: %s" % ui_only)
    print()

    # ---- 3. Age spread ----------------------------------------------------
    ages = Counter()
    for civ in fu:
        for blk in fu[civ].get("Buildings", []):
            for u in blk.get("Units", []):
                ages[u.get("RequiredAge")] += 1
    print("RequiredAge histogram: %s" % dict(sorted(
        ages.items(), key=lambda kv: (kv[0] is None, kv[0]))))
    print()

    print("=" * 72)
    print("READING")
    print("  A high building-match rate means the panel file was GENERATED by")
    print("  walking the tree (bucketing rows by Building ID), so the tree is")
    print("  the authority and the panel is a cache of it.  UI-only fields")
    print("  (PrereqStringID/... ) then describe how the preview RENDERS it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
