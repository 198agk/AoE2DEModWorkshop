// The app declares two commands of its own, and both need a permission entry
// before the page is allowed to call them.
//
// Why this file has to say it
// ---------------------------
// The page is served from `http://127.0.0.1:<random port>`, which Tauri counts
// as a REMOTE origin (tauri-2.12.5/src/webview/mod.rs:1961 -- `is_local_url`
// only accepts `tauri://`, the devUrl/frontendDist origin, and custom
// protocols).  Every IPC call from a remote origin is therefore checked against
// the ACL, custom commands included: the rejection in
// webview/mod.rs:2076-2109 fires when `!is_local` even with no app manifest.
//
// So `online_session` and `online_login` each need an `allow-*` permission, and
// the shortest honest way to get one is to let tauri-build generate it from a
// command list.  tauri-build-2.7.4/src/acl.rs:284-295 writes
// `allow-<command>` / `deny-<command>` into `permissions/autogenerated/`.
//
// Keep this list equal to the `invoke_handler` list in `src/main.rs`.  A command
// that is registered but not listed here compiles, runs, and then fails at
// runtime on the shipped exe with "Command online_x not allowed by ACL" --
// which is exactly the failure that made the window buttons dead on 2026-11-14.
fn main() {
    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(
            tauri_build::AppManifest::new().commands(&["online_session", "online_login"]),
        ),
    )
    .expect("tauri-build failed");
}
