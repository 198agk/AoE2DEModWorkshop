r"""Write `project.json`: one machine-readable description of this tool.

Why a generated file instead of a hand-written one: every hand-maintained
description in this repository has drifted, and the drift is invisible because a
stale description still parses.  README's intent table was a row short for a
day; the suite count in the verification command said 116 against a registry of
138; the schema's own prose claimed a thing was never measured after a run had
done it.  A file that is *derived* cannot disagree with the tree unless it is out
of date, and `_probe/test_project_json.py` makes "out of date" a red check.

What it declares, and why each part earns its place:

  version            the schema_version the file was generated from, so a reader
                     can tell whether it is looking at the same tool it expects
  commands           how to start it and how to verify it -- the two things a
                     newcomer needs and the two things a stale README gets wrong
  intents            every intent with its title, strategy, fields, and whether a
                     SENTENCE can reach it (a plugin intent cannot, and saying so
                     here is what stops another screen from advertising it)
  routes             the HTTP surface the page and any other client talk to
  wording            where the screen's words live, and in which locales
  delivery           the two folder shapes a build can produce, because "one
                     build, two mods" is the least guessable part of this tool
  files              the schema files that another program would have to read

Run:  python tools\describe.py            (writes project.json)
      python tools\describe.py --check    (exit 1 if the file is stale)
"""

import argparse
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

OUT = os.path.join(ROOT, "project.json")


def _read_json(path):
    with io.open(path, "r", encoding="utf-8-sig") as fh:
        return json.load(fh)


def _suite_count():
    """How many suites the runner registers -- read with ast, not a regex.

    A `re` over `run_suites.py` is fooled by a `]` inside a comment; the registry
    probe learned that on 2026-10-25 and this file must not relearn it.
    """
    import ast
    with io.open(os.path.join(ROOT, "_probe", "run_suites.py"),
                 "r", encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "SUITES" for t in node.targets):
            return len(node.value.elts)
    return 0


def build():
    from aoe2mod.intent import compiler as C
    from aoe2mod.ui import locale as LO
    from aoe2mod.ui import nl

    intents_raw, bindings = C.load_schema()
    table = LO.load()

    intents = []
    for key, spec in intents_raw["intents"].items():
        comp = spec.get("compile") or {}
        intents.append({
            "id": key,
            "title": spec.get("title") or key,
            "strategy": comp.get("strategy"),
            "fields": sorted((spec.get("fields") or {})),
            "required": sorted(k for k, v in (spec.get("fields") or {}).items()
                               if (v or {}).get("required")),
            "by_sentence": nl.sentence_reachable(key, spec),
            "mod_contains_dat": bool(comp.get("mod_contains_dat")),
        })

    routes = _routes()

    return {
        "$comment": "Generated by tools/describe.py from the live schema. Do not "
                    "edit by hand: _probe/test_project_json.py fails when this file "
                    "disagrees with the tree.",
        "name": "帝国时代 2 决定版 · 本地模组工坊",
        "schema_version": intents_raw.get("schema_version"),
        "targets_dat_version": intents_raw.get("targets_dat_version"),
        "commands": {
            "start": "双击安装包装出来的 AoE2 DE Mod Workshop.exe",
            "verify_quick": "python _probe/run_suites.py",
            "verify_long": "python _probe/run_long.py",
            "suites": {"python": _suite_count(), "node": 1},
            # A bare command, not this machine's interpreter path: the file is
            # published, and that path said more about the machine than about the
            # project.  Any Python 3.12+ on PATH runs the two commands above.
            "python": "python",
        },
        "intents": intents,
        "intents_by_sentence": sorted(i["id"] for i in intents if i["by_sentence"]),
        "intents_api_only": sorted(i["id"] for i in intents if not i["by_sentence"]),
        "routes": routes,
        "wording": {
            # `locale.load()` returns the flat key->text mapping, not the whole
            # document, so the locale name comes from the file it read.
            "file": "aoe2mod/schema/locales/zh.json",
            "locale": LO.DEFAULT_LOCALE,
            "keys": len(table),
        },
        "delivery": {
            "single_mod": "一份模组：只有 .dat，或只有 widgetui —— 单一策略的意图",
            "split_pair": ("一次 build 产出两个模组：`X`（数据半边）与 `X（界面）`。"
                           "同一个文件夹里 .dat 与 widgetui 只有一半生效，实测五次空框"),
            "must_enable_both": True,
            "info_json_keys": (intents_raw.get("mod") or {}).get("info_json_keys"),
        },
        "files": {
            "schema": sorted(
                os.path.join("aoe2mod", "schema", n)
                for n in os.listdir(os.path.join(ROOT, "aoe2mod", "schema"))
                if n.endswith(".json")),
            "entry": "tools/run_ui.py",
            "ui": "aoe2mod/ui/static/index.html",
        },
    }


def _routes():
    """Read the route table out of server.py, so this cannot list a route twice.

    The two methods are split at their own `def`, because GET and POST bodies are
    both just `if path == "...":` lines -- a single regex over the file would
    report every POST route as a GET.  That mistake was made once here: the first
    version found 24 GET routes and zero POST.
    """
    src = io.open(os.path.join(ROOT, "aoe2mod", "ui", "server.py"),
                  encoding="utf-8").read()
    cut = src.find("def do_POST")
    get_part = src if cut < 0 else src[:cut]
    post_part = "" if cut < 0 else src[cut:]
    # The POST body ends where the next method starts.
    end = post_part.find("\n        def ", 5)
    if end > 0:
        post_part = post_part[:end]
    pattern = r'if path == "(/api/[a-z0-9\-]+)"'
    return {"get": sorted(set(re.findall(pattern, get_part))),
            "post": sorted(set(re.findall(pattern, post_part)))}


def render(doc):
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=False) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="compare with the checked-in file instead of writing")
    args = ap.parse_args(argv)

    text = render(build())
    if args.check:
        if not os.path.isfile(OUT):
            print("project.json is missing -- run tools/describe.py")
            return 1
        current = io.open(OUT, encoding="utf-8", newline="").read()
        if current != text:
            print("project.json is STALE -- run tools/describe.py")
            return 1
        print("project.json matches the tree (%d bytes)" % len(text.encode("utf-8")))
        return 0

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (OUT, len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
