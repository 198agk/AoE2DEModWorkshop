def vendor_sldencode():
    """Vendor the SLD repainter.

    One mechanical patch: the research file imports its sibling as a top-level
    module (`import sldlib as S`), because `_probe/` is not a package.  Inside
    `aoe2mod/game/` the sibling is `sld.py`, so the import becomes relative.
    """
    if not os.path.exists(SRC_SLDENCODE):
        raise SystemExit("FATAL: no _probe/sldencode.py to vendor")
    src = open(SRC_SLDENCODE, "r", encoding="utf-8").read()
    patched = src.replace("\nimport sldlib as S\n", "\nfrom . import sld as S\n")
    if patched == src:
        raise SystemExit("FATAL: sldencode.py no longer has the expected "
                         "'import sldlib as S' line; refusing to vendor blind")
    dst = os.path.join(PKG, "game", "sldencode.py")
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(patched)
    return dst


