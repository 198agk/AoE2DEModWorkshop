# -*- coding: utf-8 -*-
"""sync_engine.py -- vendor the PROVEN .dat engine into the product package.

The research phase produced two files that are verified byte-exact:

  _probe/datparse/parse_dat.py       5/5 datasets parse to EXACT EOF
  _probe/serializer/write_dat.py     5/5 datasets byte-exact round-trip

They must NOT be rewritten by hand -- that would discard the verification.
This script copies them verbatim into ``aoe2mod/dat/`` and applies exactly one
mechanical patch: the writer's ad-hoc sys.path hack that reached into
``_probe/datparse`` is replaced by a normal intra-package import.

It also copies the semantic tables and the branch-aware effect vocabulary
tables, and records a sha256 of every source file, so drift in the research
tree is detectable.

Run:  python tools/sync_engine.py
"""
import hashlib
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROBE = os.path.join(ROOT, "_probe")
PKG = os.path.join(ROOT, "aoe2mod")

SRC_PARSER = os.path.join(PROBE, "datparse", "parse_dat.py")
SRC_WRITER = os.path.join(PROBE, "serializer", "write_dat.py")
SRC_LOCATOR = os.path.join(PROBE, "datparse", "intent_patch.py")
# The `.sld` reader/renderer.  Verified tree-wide before vendoring: 15,484 of
# 15,484 shipped files walk to EXACT EOF, 4,850,222 frames, zero frame_index
# discontinuities, and the header's num_frames matches the walked count in every
# file.  It is stdlib-only (struct), so it needs no patch -- copied verbatim.
SRC_SLDLIB = os.path.join(PROBE, "sldlib.py")
# The `.sld` ENCODER.  It cannot build a file from scratch -- every frame that
# carries a `main` layer also carries an `unknown2` layer (4,737,215 frames,
# zero exceptions), and unknown2's size is not a function of main's run list,
# so it is not derivable.  What it does instead is repaint an existing file's
# main blocks in place, which is enough to put new art on an existing
# animation.  Verified by _probe/test_sld_encode.py (identity block copy is
# byte-exact, chequerboard re-decodes within 2, non-main layers untouched).
SRC_SLDENCODE = os.path.join(PROBE, "sldencode.py")
SRC_NAMES = [
    (os.path.join(PROBE, "semantic", "unit_names.json"), "unit_names.json"),
    (os.path.join(PROBE, "semantic", "tech_names.json"), "tech_names.json"),
]
SRC_INI = os.path.join(PROBE, "..", "aoe2docs", "AGE3NamesV0007.ini")

# The three effect vocabulary tables.  They are GENERATED, not written by hand:
# ``_probe/schema/build_schema.py`` walks AGE's own version branches (via
# ``_probe/schema/cpp_branch.py``) and evaluates them FOR AoE2:DE.  Copying the
# generated result -- rather than regenerating it here -- keeps this script
# runnable without the AGE source tree, while still making drift detectable.
#
# These tables used to be copied by hand, and the package copy silently kept an
# older generation that named attributes and classes from Star Wars/AoE1
# branches (attribute 104 "Carbon Costs" instead of "Wood Costs"; the whole
# class table shifted one slot).  Vendoring them removes that failure mode.
SRC_EFFECT_TABLES = [
    (os.path.join(PROBE, "schema", "effect_command_types.json"),
     "effect_command_types.json"),
    (os.path.join(PROBE, "schema", "effect_attributes.json"),
     "effect_attributes.json"),
    (os.path.join(PROBE, "schema", "armor_classes.json"),
     "armor_classes.json"),
]

# Guard for vendor_effect_tables().  This is the opening of BRANCH_RULE in
# _probe/schema/build_schema.py; a table whose note does not carry it came from
# the older regex generator.  Kept as a literal so this script still runs when
# the probe tree (and therefore build_schema.py) is absent -- a mismatch only
# ever produces a loud refusal, never a silent wrong copy.
BRANCH_RULE_MARKER = "walked AGE's own version branches and evaluated them for AoE2:DE"

# The Chinese label table is generated from those three by
# _probe/schema/build_labels_zh.py.  It is OPTIONAL at runtime (a stripped
# install just shows AGE's English names), so it is copied without the branch
# guard above.  It must stay generated: hand-typing 200+ ids is how an id gets
# silently attached to the wrong name.
SRC_LABEL_ZH = os.path.join(PROBE, "schema", "effect_labels_zh.json")

# The civilization resource id -> name tables, generated by
# ``_probe/schema/build_resource_labels.py`` from the GAME'S OWN resource-name
# block: resources/<locale>/strings/key-value/key-value-strings-utf8.txt at
# string id 15000 + resource type id.  Cost slots store a resource as an id, and
# eight of the ids the shipped data charges are not declared resources -- without
# this table the UI says "成本 type 506".
#
# The game's block replaces AGE's AGE3NamesV0007.ini, which named 271 slots and
# could not name 501/506/508/513/514 AT ALL.  Same honesty rule as before: the
# generator DROPS the slots the game calls "Unused Resource NNN" (223 of 551) so
# a miss falls back to a number rather than printing "Unused" as a resource.
# AGE is deliberately NOT used as a fallback -- every id AGE could add is one the
# game itself reserves as unused.
#
# The translation comes from the same block in the zh locale, so it is the
# game's official wording, not a hand-written subset.  It is still OPTIONAL at
# runtime (a stripped install shows the English name), so it is copied without a
# guard.
SRC_RESOURCE_LABELS = [
    (os.path.join(PROBE, "schema", "resource_labels.json"),
     "resource_labels.json"),
    (os.path.join(PROBE, "schema", "resource_labels_zh.json"),
     "resource_labels_zh.json"),
]

# The effect attribute id -> name tables, generated by
# ``_probe/schema/build_attribute_labels.py`` from the GAME'S OWN block at string
# id 12200 + attribute id.  ``effect_attributes.json`` (AGE's table) names 89 ids
# and an attribute it does not name is refused rather than guessed -- right, but
# it cost 160 shipped commands, and the game names all 11 of those ids.
#
# This SUPPLEMENTS AGE's table rather than replacing it, and the generator says
# why with numbers: 66 of AGE's names differ from the game's and 54 sit on a live
# command, so swapping wholesale would reword 5,194 of 6,420 attribute-modifier
# commands while claiming to fix 160.  Same honesty rule: slots the game fills
# with "Unused ..." or "<!--RESERVED-->" are dropped, so a miss falls back to a
# number.  English required, the zh translation optional.
SRC_ATTRIBUTE_LABELS = [
    (os.path.join(PROBE, "schema", "attribute_labels.json"),
     "attribute_labels.json"),
    (os.path.join(PROBE, "schema", "attribute_labels_zh.json"),
     "attribute_labels_zh.json"),
]

# The exact block in _probe/serializer/write_dat.py that adds _probe/datparse
# to sys.path.  Replaced with a package-relative import.
WRITER_PATH_HACK = re.compile(
    r"sys_path_guard = os\.path\.join\(\n"
    r"    os\.path\.dirname\(os\.path\.dirname\(os\.path\.abspath\(__file__\)\)\), "
    r"\"datparse\"\)\n"
    r"if sys_path_guard not in os\.sys\.path:\n"
    r"    os\.sys\.path\.insert\(0, sys_path_guard\)\n"
    r"import parse_dat as _pd\s*#[^\n]*\n")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ensure_dirs():
    for sub in ("dat", "semantic/data", "intent", "mod", "game",
                "schema", "tests"):
        os.makedirs(os.path.join(PKG, sub), exist_ok=True)


def vendor_parser():
    dst = os.path.join(PKG, "dat", "parser.py")
    shutil.copyfile(SRC_PARSER, dst)
    return dst


def vendor_writer():
    dst = os.path.join(PKG, "dat", "writer.py")
    src = open(SRC_WRITER, encoding="utf-8").read()

    if not WRITER_PATH_HACK.search(src):
        raise SystemExit(
            "FATAL: the writer's sys.path hack no longer matches.\n"
            "The upstream file changed shape; re-derive the patch instead of\n"
            "silently shipping a writer that cannot find the parser.")

    src = WRITER_PATH_HACK.sub("from . import parser as _pd\n", src, count=1)

    # the __main__ helper also does `import parse_dat`
    src = src.replace("    import parse_dat\n",
                      "    from aoe2mod.dat import parser as parse_dat\n")
    src = src.replace("    p = parse_dat.Parser(raw)\n",
                      "    p = parse_dat.Parser(raw)\n")

    header = (
        '"""write_dat.py -- re-serializer for AoE2 DE ``.dat`` files.\n\n'
        "VENDORED VERBATIM from _probe/serializer/write_dat.py by\n"
        "tools/sync_engine.py.  Do not edit here; edit the research copy and\n"
        "re-run the sync, or the verification lineage is lost.\n"
        '"""\n')
    # replace the original module docstring, keep everything after it
    body = src.split('"""', 2)[-1]
    out = header + body
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(out)
    return dst


def vendor_locator():
    """Vendor the record-locating walker (marks field offsets).

    The walker mirrors genieutils' Unit::serializeObject() and is the only
    thing in the toolkit that knows where a unit's stats live.  Copying it
    rather than re-deriving it keeps a single verified code path.
    """
    dst = os.path.join(PKG, "dat", "locate.py")
    src = open(SRC_LOCATOR, encoding="utf-8").read()

    # Replace the research-tree import with the packaged one.
    old_import = "import parse_dat as P\n"
    if old_import not in src:
        raise SystemExit(
            "FATAL: the locator no longer imports bare 'parse_dat'.  Re-derive\n"
            "the patch instead of shipping a locator that cannot find it.")
    src = src.replace(old_import, "from . import parser as P\n", 1)

    # Drop the human demo: the product calls locate()/find_units() directly.
    cut = src.find('if __name__ == "__main__":')
    if cut < 0:
        raise SystemExit("FATAL: locator has no __main__ guard to trim.")
    src = src[:cut].rstrip() + "\n"

    header = (
        '"""locate.py -- find and mark the byte offsets of unit records.\n\n'
        "VENDORED from _probe/datparse/intent_patch.py by tools/sync_engine.py\n"
        "(the demo main() is trimmed).  Do not edit here; edit the research copy\n"
        "and re-run the sync, or the verification lineage is lost.\n\n"
        "``locate(data)`` returns ``(civs, civs_start, gv, tail)`` and\n"
        "``find_units(civs, unit_id)`` returns every per-civ physical record.\n"
        '"""\n')
    body = src.split('"""', 2)[-1]
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(header + body)
    return dst


def vendor_effect_tables():
    """Vendor the branch-aware effect vocabulary tables.

    Refuses to copy a table that was not produced by the branch-aware
    generator: the tell-tale is the ``note`` naming the branch rule.  Without
    this guard a stale table from the old regex generator (which let the Star
    Wars/AoE1 entries overwrite the AoE2 ones) would be accepted silently --
    exactly the bug this function exists to prevent.
    """
    out = []
    for src, name in SRC_EFFECT_TABLES:
        if not os.path.exists(src):
            raise SystemExit(
                "FATAL: %s is missing.  Run _probe/schema/build_schema.py first."
                % os.path.relpath(src, ROOT))
        data = json.load(open(src, encoding="utf-8"))
        if BRANCH_RULE_MARKER not in (data.get("note") or ""):
            raise SystemExit(
                "FATAL: %s does not name the version branch it was generated\n"
                "for.  It predates the branch-aware generator and may hold\n"
                "another engine's names.  Re-run _probe/schema/build_schema.py."
                % os.path.relpath(src, ROOT))
        dst = os.path.join(PKG, "schema", name)
        shutil.copyfile(src, dst)
        out.append((dst, name, len(open(dst, "rb").read())))
    if os.path.exists(SRC_LABEL_ZH):
        dst = os.path.join(PKG, "schema", "effect_labels_zh.json")
        shutil.copyfile(SRC_LABEL_ZH, dst)
        out.append((dst, "effect_labels_zh.json", len(open(dst, "rb").read())))
    # The English resource table is REQUIRED -- it is what turns an unnamed cost
    # type into a name -- while the translation is optional.
    for src, name in SRC_RESOURCE_LABELS:
        if name.endswith("_zh.json") and not os.path.exists(src):
            continue
        if not os.path.exists(src):
            raise SystemExit(
                "FATAL: %s is missing.  Run _probe/schema/build_resource_labels.py "
                "first." % os.path.relpath(src, ROOT))
        dst = os.path.join(PKG, "schema", name)
        shutil.copyfile(src, dst)
        out.append((dst, name, len(open(dst, "rb").read())))
    # Same rule for the attribute tables: the English one is what un-refuses the
    # 160 commands whose attribute AGE does not name.
    for src, name in SRC_ATTRIBUTE_LABELS:
        if name.endswith("_zh.json") and not os.path.exists(src):
            continue
        if not os.path.exists(src):
            raise SystemExit(
                "FATAL: %s is missing.  Run "
                "_probe/schema/build_attribute_labels.py first."
                % os.path.relpath(src, ROOT))
        dst = os.path.join(PKG, "schema", name)
        shutil.copyfile(src, dst)
        out.append((dst, name, len(open(dst, "rb").read())))
    return out


def vendor_sldlib():
    """Vendor the SLD sprite reader/renderer.

    Copied VERBATIM: it is stdlib-only and already byte-exact-verified over the
    whole shipped corpus, so any hand edit here would discard that verification.
    """
    if not os.path.exists(SRC_SLDLIB):
        raise SystemExit("FATAL: no _probe/sldlib.py to vendor")
    dst = os.path.join(PKG, "game", "sld.py")
    shutil.copyfile(SRC_SLDLIB, dst)
    return dst


def vendor_sldencode():
    """Vendor the SLD repainter.

    One mechanical patch: the research file imports its sibling as a top-level
    module (`import sldlib as S`), because `_probe/` is not a package.  Inside
    `aoe2mod/game/` the sibling is `sld.py`, so the import becomes relative.
    """
    if not os.path.exists(SRC_SLDENCODE):
        raise SystemExit("FATAL: no _probe/sldencode.py to vendor")
    src = open(SRC_SLDENCODE, "r", encoding="utf-8").read()
    patched = src.replace("\nimport sldlib as S\n", "\nfrom . import sld as S\n")
    if patched == src:
        raise SystemExit("FATAL: sldencode.py no longer has the expected "
                         "'import sldlib as S' line; refusing to vendor blind")
    dst = os.path.join(PKG, "game", "sldencode.py")
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(patched)
    return dst


def vendor_names():
    out = []
    for src, name in SRC_NAMES:
        dst = os.path.join(PKG, "semantic", "data", name)
        shutil.copyfile(src, dst)
        out.append((dst, len(open(dst, "rb").read())))
    return out


def write_pkg_inits():
    for sub, doc in (
        ("", "AoE2 DE mod toolkit kernel."),
        ("dat", "Binary .dat engine (vendored, byte-exact verified)."),
        ("semantic", "Entity/technology name resolution."),
        ("intent", "Intent schema + compiler."),
        ("mod", "Mod folder emission."),
        ("game", "Game/profile/mod location discovery."),
        ("tests", "Invariant tests."),
    ):
        d = os.path.join(PKG, sub) if sub else PKG
        p = os.path.join(d, "__init__.py")
        if not os.path.exists(p):
            with open(p, "w", encoding="utf-8") as fh:
                fh.write('"""%s"""\n' % doc)


def main():
    ensure_dirs()
    manifest = {"sources": {}}

    for label, path in (("parser", SRC_PARSER), ("writer", SRC_WRITER),
                        ("locator", SRC_LOCATOR), ("sldlib", SRC_SLDLIB),
                        ("sldencode", SRC_SLDENCODE)):
        manifest["sources"][label] = {
            "path": os.path.relpath(path, ROOT).replace("\\", "/"),
            "sha256": sha256(path),
            "bytes": os.path.getsize(path),
        }

    p = vendor_parser()
    w = vendor_writer()
    loc = vendor_locator()
    sld = vendor_sldlib()
    enc = vendor_sldencode()
    names = vendor_names()
    tables = vendor_effect_tables()
    write_pkg_inits()

    for label, dst in (("parser", p), ("writer", w), ("locator", loc),
                       ("sldlib", sld), ("sldencode", enc)):
        manifest["vendored_" + label] = {
            "path": os.path.relpath(dst, ROOT).replace("\\", "/"),
            "sha256": sha256(dst),
            "bytes": os.path.getsize(dst),
        }
    manifest["data"] = [
        {"path": os.path.relpath(d, ROOT).replace("\\", "/"), "bytes": n}
        for d, n in names
    ]
    manifest["effect_tables"] = [
        {"path": os.path.relpath(d, ROOT).replace("\\", "/"),
         "bytes": n, "sha256": sha256(d)}
        for d, _name, n in tables
    ]

    mp = os.path.join(PKG, "ENGINE_PROVENANCE.json")
    with open(mp, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")

    print("vendored parser -> %s (%d B)"
          % (os.path.relpath(p, ROOT), os.path.getsize(p)))
    print("vendored writer -> %s (%d B)"
          % (os.path.relpath(w, ROOT), os.path.getsize(w)))
    print("vendored locator-> %s (%d B)"
          % (os.path.relpath(loc, ROOT), os.path.getsize(loc)))
    print("vendored sldlib -> %s (%d B)"
          % (os.path.relpath(sld, ROOT), os.path.getsize(sld)))
    print("vendored sldenc -> %s (%d B)"
          % (os.path.relpath(enc, ROOT), os.path.getsize(enc)))
    for d, n in names:
        print("copied data     -> %s (%d B)" % (os.path.relpath(d, ROOT), n))
    for d, name, n in tables:
        print("effect table    -> %s (%d B)" % (os.path.relpath(d, ROOT), n))
    print("provenance      -> %s" % os.path.relpath(mp, ROOT))

    # the parser's own sha must survive byte-for-byte
    assert sha256(p) == sha256(SRC_PARSER), "parser copy is not byte-identical"
    print("parser copy is byte-identical to the verified research file: OK")
    assert sha256(sld) == sha256(SRC_SLDLIB), "sldlib copy is not byte-identical"
    print("sldlib copy is byte-identical to the verified research file: OK")
    # sldencode gets one import line rewritten, so it cannot be byte-identical.
    # Assert the patched copy equals the source under exactly that one change,
    # which is stricter than comparing lengths.
    _enc_src = open(SRC_SLDENCODE, "r", encoding="utf-8").read()
    _enc_dst = open(enc, "r", encoding="utf-8").read()
    assert _enc_dst == _enc_src.replace("\nimport sldlib as S\n",
                                        "\nfrom . import sld as S\n"), \
        "sldencode copy differs from the research file by more than the import"
    assert "import sldlib" not in _enc_dst, \
        "the vendored sldencode still imports the research module name"
    print("sldencode copy differs from the research file only in its import: OK")
    # and the generated tables must arrive unmodified
    for src, name in SRC_EFFECT_TABLES:
        assert sha256(os.path.join(PKG, "schema", name)) == sha256(src), \
            "effect table %s is not byte-identical to the generated file" % name
    print("branch-aware effect tables are byte-identical to the generated files: OK")
    if os.path.exists(SRC_LABEL_ZH):
        assert sha256(os.path.join(PKG, "schema", "effect_labels_zh.json")) \
            == sha256(SRC_LABEL_ZH), "effect_labels_zh.json is not byte-identical"
    # and the resource name tables, which are generated from the game's own
    # 15000+type string block (not from AGE's ini -- see build_resource_labels.py)
    for src, name in SRC_RESOURCE_LABELS:
        if os.path.exists(src):
            assert sha256(os.path.join(PKG, "schema", name)) == sha256(src), \
                "resource label table %s is not byte-identical to the generated file" % name
    print("resource name tables are byte-identical to the generated files: OK")
    # and the attribute name tables, generated from the game's own 12200+attribute
    # id block (not from AGE's effect_attributes.json -- see
    # build_attribute_labels.py)
    for src, name in SRC_ATTRIBUTE_LABELS:
        if os.path.exists(src):
            assert sha256(os.path.join(PKG, "schema", name)) == sha256(src), \
                "attribute label table %s is not byte-identical to the generated file" % name
    print("attribute name tables are byte-identical to the generated files: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
